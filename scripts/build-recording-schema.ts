// S.sarif is the single shape-contract source. Native semantic checks and the
// producer→consumer gate remain necessary; JSON Schema cannot encode refinements.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { z, sarif } from "../src/schemas.ts";

export function recordingSchema(input: z.ZodType = sarif) {
  return z.toJSONSchema(input, {
    target: "draft-2020-12",
    io: "input",
    unrepresentable: "throw",
    reused: "ref",
    override({ zodSchema }) {
      // Zod emits RegExp.source but cannot represent JS flags in JSON Schema.
      for (const check of zodSchema._zod.def.checks ?? []) {
        const def = check._zod.def;
        const pattern = "pattern" in def ? def.pattern : undefined;
        if (pattern instanceof RegExp && pattern.flags) {
          throw new Error(
            "Recording regex flags are not portable to JSON Schema; use explicit character classes.",
          );
        }
      }
    },
  });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const destination = new URL("../cli/protocol/recording-v2.schema.json", import.meta.url);
  const schema = recordingSchema();
  schema.$comment = "Generated by scripts/build-recording-schema.ts from src/schemas.ts S.sarif (input shape). Zod refinements and readRecord cross-field/authorization checks remain server semantics; see docs/development.md.";
  const output = JSON.stringify(schema, null, 2) + "\n";
  if (process.argv.includes("--check")) {
    let current;
    try {
      current = await readFile(destination, "utf8");
    } catch {}
    if (current !== output) {
      throw new Error(
        "Recording schema is stale. Run npm run build:recording-schema and coordinate CLI/server contract changes.",
      );
    }
    console.log("Bundled recording schema matches server input shape.");
  } else {
    await mkdir(new URL("../cli/protocol/", import.meta.url), { recursive: true });
    await writeFile(destination, output);
    console.log("Generated " + fileURLToPath(destination));
  }
}
